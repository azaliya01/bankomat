
import 'dart:io';

void main() {
  // тут лежит наш баланс, для начала 1000
  int balance = 1000;

  // бесконечный цикл, чтобы меню не закрывалось после каждого действия
  while (true) {
    // рисуем менюшку на экране
    print(' Интерактивний банкомат');
    print('1. Проверить баланс');
    print('2. Пополнить счет');
    print('3. Снять наличные');
    print('4. Выход');
    stdout.write('Выберите пункт меню: ');

    // считываем то, что ввел пользователь
    String? input = stdin.readLineSync();
    // пробуем перевести строку в число
    int? choice = int.tryParse(input ?? '');

    // если ввели буквы вместо цифры, то ругаемся и кидаем continue в начало цикла
    if (choice == null) {
      print('Ошибка: введено не число. пж введите номер пункта меню.');
      continue;
    }

    // смотрим какой пункт выбрал человек
    switch (choice) {
      case 1:
        // просто показываем сколько денег на счету
        print('Ваш текущий баланс: $balance руб.');
        break;
      case 2:
        // спрашиваем сколько хочет положить
        stdout.write('Введите сумму для пополнения: ');
        int? amount = int.tryParse(stdin.readLineSync() ?? '');
        // проверяем, что сумма нормальная и больше нуля
        if (amount != null && amount > 0) {
          balance += amount; // добавляем к нашему балансу
          print('Счет успешно пополнен. Новый баланс: $balance руб.');
        } else {
          print('Ошибка: некорректная сумма.');
        }
        break;
      case 3:
        // спрашиваем сколько снять хочет
        stdout.write('Введите сумму для снятия: ');
        int? amount = int.tryParse(stdin.readLineSync() ?? '');
        // проверяем что сумма больше нуля
        if (amount != null && amount > 0) {
          // проверяем, хватает ли вообще денег на балансе
          if (amount <= balance) {
            balance -= amount; // вычитаем из баланса
            print('Операция выполнена. Остаток: $balance руб.');
          } else {
            print('Ошибка: недостаточно средств на счете.');
          }
        } else {
          print('Ошибка: некорректная сумма.');
        }
        break;
      case 4:
        // завершаем работу программы
        print('Спасибо за использование нашего сервиса! покашки.');
        return;
      default:
        // если ввели число, но такого пункта в меню нет
        print('Ошибка: такого пункта меню не существует. Выберите от 1 до 4.');
    }
  }
}
